CREATE TABLE TELEFONE (
    CPF VARCHAR(11) NOT NULL,
    Telefone VARCHAR(15) NOT NULL,
    CONSTRAINT pk_telefone PRIMARY KEY (CPF, Telefone),
    CONSTRAINT fk_telefone_pessoa FOREIGN KEY (CPF)
        REFERENCES PESSOA (CPF)
        ON DELETE CASCADE
);

