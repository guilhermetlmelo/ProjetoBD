

CREATE TABLE PEDIDO (
    ID_Pedido         INTEGER   NOT NULL,
    ID_Atendimento    INTEGER   NOT NULL,
    Codigo_Prod       INTEGER   NOT NULL,
    Quantidade        INTEGER   NOT NULL,
    Data_Hora_Pedido  TIMESTAMP NOT NULL,
    CONSTRAINT pk_pedido PRIMARY KEY (ID_Pedido, ID_Atendimento, Codigo_Prod),
    CONSTRAINT fk_pedido_atendimento FOREIGN KEY (ID_Atendimento) REFERENCES ATENDIMENTO (ID_Atendimento),
    CONSTRAINT fk_pedido_produto FOREIGN KEY (Codigo_Prod) REFERENCES PRODUTO (Codigo_Prod),
    CONSTRAINT ck_pedido_quantidade CHECK (Quantidade > 0)
);

